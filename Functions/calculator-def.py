num1 = 10
num2 = 5

def addition():
    add = num1 + num2
    print(f"Addition result is: {add}")

def substraction():
    sub = num1 - num2
    print(f"substraction result is: {sub}")

def multiplication():
    mul = num1 * num2
    print(f"multiplication result is: {mul}")

def division():
    div = num1 / num2
    print(f"division result is: {div}")


addition()
substraction()
multiplication()
division()


